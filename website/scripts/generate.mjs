// Generates the data-driven parts of the site from ../data/*.json:
//   docs/apis/<id>.mdx     one page per API
//   docs/wpt.mdx           Web Platform Tests pass rates
//   sidebars.generated.json  the API list for the docs sidebar
//   src/data/*.json        data for the React components
//   src/data/idl-summary.json  coverage summary (existence pass) for the pages
//   src/data/site.json     site settings shared with the components (maintainer's engine)
//   static/data/*.json     the open data, served as files (+ idl-search.json)
// The per-spec and per-interface Coverage pages are added by plugins/coverage.mjs.
// All of these are git-ignored and rebuilt by `npm run build` / `npm start`.
// Do not edit them by hand; change the data or this script instead.

import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { summarize, searchRows, interfaceIndex, interfacePath } from './coverage.mjs';
import { MAINTAINER_ENGINE } from '../../src/order.mjs';

export const BANNER = '{/* Generated by website/scripts/generate.mjs from data/*.json. Do not edit by hand. */}';

export const STATUS_LABEL = {
  supported: 'Supported',
  partial: 'Partial',
  stub: 'Stub',
  missing: 'Missing',
};

// Escapes text for MDX prose: markdown and JSX punctuation get a backslash.
export function mdxText(s) {
  return String(s ?? '')
    .replace(/[\\`*_{}[\]<>|~!#]/g, (c) => `\\${c}`)
    .replace(/\r?\n/g, ' ');
}

// Inline code span that is safe for any content.
export function mdxCode(s) {
  const text = String(s ?? '').replace(/\r?\n/g, ' ');
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const fence = '`'.repeat(longest + 1);
  const pad = text.startsWith('`') || text.endsWith('`') ? ' ' : '';
  return `${fence}${pad}${text}${pad}${fence}`;
}

const link = (text, url) => `[${mdxText(text)}](${url})`;

export const SITE = 'https://domparity.github.io';
export const ISSUES_NEW = 'https://github.com/domparity/domparity.github.io/issues/new';
const MAX_FIELD = 600;
const clip = (s) => {
  const t = String(s ?? '');
  return t.length > MAX_FIELD ? `${t.slice(0, MAX_FIELD)}…` : t;
};
const fence = (s) => '`' + String(s ?? '').replace(/`/g, "'") + '`';

// A link that opens a new GitHub issue with title and body filled in.
export function issueUrl(title, body) {
  return `${ISSUES_NEW}?${new URLSearchParams({ title, body, labels: 'accuracy' }).toString()}`;
}

// Prefilled "wrong result" report for one API in one engine.
export function featuredReport(api, engine, r, data) {
  const STATUS = STATUS_LABEL[r.status] ?? r.status;
  const lines = [
    `**Engine:** ${engine.engine} ${engine.version ?? ''}${engine.setup ? ` (window created with ${fence(engine.setup)})` : ''}`,
    `**API:** ${api.title} (${fence(api.id)}): ${SITE}/apis/${api.id}`,
    `**Status shown:** ${STATUS}`,
    `**Probed:** ${data.date.slice(0, 10)} on Node.js ${data.node}`,
    '',
  ];
  if (r.status === 'missing') {
    lines.push(
      `**Expected:** ${api.existsDescription ? `it exists: ${api.existsDescription}` : "the API exists in this engine's window."}`,
      `**Observed:** ${r.error ? fence(clip(r.error)) : api.existsDescription ? 'the existence test fails' : 'not defined'}`,
      '',
    );
  }
  for (const f of r.failed) {
    const check = api.checks.find((c) => c.id === f.id);
    lines.push(
      `### Check ${fence(f.id)}`,
      `**Expected (per the spec):** ${clip(check?.description ?? '')}`,
      `**Spec:** ${check?.spec ?? api.spec}`,
      `**Observed:** ${f.error ? fence(clip(f.error)) : 'no error text'}`,
      ...(f.logged ?? []).map((l) => `**Logged by the engine:** ${fence(clip(l))}`),
      '',
    );
  }
  if (r.passed.length) lines.push(`Checks that work: ${r.passed.map(fence).join(', ')}`, '');
  lines.push('### What is wrong?', '', '<!-- Which result is wrong, what you expected and why, with a link to the specification. -->', '');
  return issueUrl(`Wrong result: ${api.title} in ${engine.engine} ${engine.version ?? ''}`.trim(), lines.join('\n'));
}

// Web IDL existence of the interfaces a featured API is about (api.interfaces),
// for one engine: whether each interface is defined and which of its members
// (from every spec) are missing. Empty when there is no coverage data.
export function idlLines(api, engineKey, idl) {
  if (!idl || !api.interfaces?.length) return [];
  const i = idl.engines.findIndex((e) => e.key === engineKey);
  if (i < 0) return [];
  const index = interfaceIndex(idl);
  const out = [];
  for (const name of api.interfaces) {
    const own = index[name];
    if (!own) continue;
    const status = idl.specs[own.spec].interfaces[name].status[i];
    const members = Object.values(idl.specs).flatMap((s) => s.interfaces[name]?.members ?? []);
    const missing = members.filter((m) => m[2][i] === '0').map((m) => m[0]);
    const page = link(name, interfacePath(name));
    if (status === '-') {
      out.push(`- ${page}: interface not defined.`);
      continue;
    }
    const shown = missing.slice(0, 12).map((m) => mdxCode(m.startsWith('@@') ? `[Symbol.${m.slice(2)}]` : m));
    const more = missing.length > shown.length ? ` and ${missing.length - shown.length} more` : '';
    out.push(
      `- ${page}: interface present${status === 'N' ? " (Node.js's own global)" : status === 'S' ? ' (a stub)' : ''}; ${members.length - missing.length} of ${members.length} members present${missing.length ? `, missing: ${shown.join(', ')}${more}` : ''}.`,
    );
  }
  return out.length ? ['Web IDL existence ([coverage](/coverage)):', '', ...out, ''] : [];
}

export function renderApiPage(api, data, idl = null) {
  const lines = [
    '---',
    `id: ${api.id}`,
    `title: ${JSON.stringify(api.title)}`,
    `description: ${JSON.stringify(api.summary)}`,
    `slug: /apis/${api.id}`,
    '---',
    '',
    BANNER,
    '',
    "import StatusBadge from '@site/src/components/StatusBadge';",
    "import ReportLink from '@site/src/components/ReportLink';",
    '',
    `${mdxText(api.summary)} Specification: ${link(api.spec.replace(/^https?:\/\//, '').split('#')[0], api.spec)}.`,
    '',
    '## Results',
    '',
    `Probed on ${data.date.slice(0, 10)} with Node.js ${data.node}.`,
    '',
  ];
  for (const engine of data.engines) {
    const r = data.results[api.id]?.[engine.key];
    if (!r) continue;
    lines.push(`### ${mdxText(engine.engine)} ${mdxText(engine.version ?? '')}`, '', `<StatusBadge status="${r.status}" />`, '');
    const report = `<ReportLink href={${JSON.stringify(featuredReport(api, engine, r, data))}} engine={${JSON.stringify(engine.engine)}} />`;
    const total = api.checks.length;
    if (r.status === 'missing') {
      lines.push(
        r.error
          ? `Missing: checking for it threw ${mdxCode(r.error)}.`
          : api.existsDescription
            ? `Missing: in this engine's window, this does not hold: ${mdxText(api.existsDescription)}`
            : 'Not defined in this engine\'s window.',
        '',
      );
    } else {
      lines.push(`${r.passed.length} of ${total} checks work.`, '');
    }
    if (r.sameAsNode) {
      lines.push(
        `The window's value is Node.js's own global (identical object), not the engine's implementation.`,
        '',
      );
    }
    lines.push(...idlLines(api, engine.key, idl));
    for (const f of r.failed) {
      const check = api.checks.find((c) => c.id === f.id);
      lines.push(`- ${check ? mdxText(check.description) : mdxCode(f.id)}`);
      if (f.error) lines.push(`  - Result: ${mdxCode(f.error)}`);
      for (const msg of f.logged ?? []) lines.push(`  - Logged by the engine: ${mdxCode(msg)}`);
    }
    if (r.failed.length) lines.push('');
    lines.push(report, '');
  }
  lines.push('## Checks', '');
  if (api.existsDescription) lines.push(`Exists when: ${mdxText(api.existsDescription)}`, '');
  for (const c of api.checks) {
    lines.push(`- ${mdxCode(c.id)}: ${mdxText(c.description)} (${link('spec', c.spec)})`);
  }
  lines.push('');
  if (api.nodeGlobal) {
    lines.push(
      '## Node.js globals',
      '',
      `Node.js defines ${mdxCode(api.nodeGlobal)} itself. Depending on the test runner and its environment, tests may see Node's version even where the engine's window has none; these results describe the engine's window only.`,
      '',
    );
  }
  if (api.workaround) lines.push('## Working around it in tests', '', mdxText(api.workaround), '');
  return lines.join('\n');
}

export function renderSidebar(data) {
  return [...data.apis]
    .sort((a, b) => a.title.localeCompare(b.title))
    .map((a) => `apis/${a.id}`);
}

const pct = (a) => `${((100 * a.passed) / a.subtests).toFixed(1)}%`;

export function renderWpt(wpt) {
  const s = wpt.source;
  const measured = Object.entries(wpt.engines).filter(([, e]) => e.measured);
  const areas = [...new Set(measured.flatMap(([, e]) => e.areas.map((a) => a.area)))];
  const lines = [
    '---',
    'id: wpt',
    'title: Web Platform Tests',
    'description: Web Platform Tests pass rates per area, where measured.',
    'slug: /wpt',
    '---',
    '',
    BANNER,
    '',
    `Pass rates of the ${link('Web Platform Tests', 'https://web-platform-tests.org/')} (WPT), the browsers' shared conformance suite, in the areas ${s.areas.map(mdxCode).join(', ')}. They complement the probes: many more tests, but only for the areas that were run.`,
    '',
    `- WPT commit: ${link(s.wptCommit.slice(0, 10), s.wptCommitUrl)}, run on ${s.date}, Node.js ${s.node}`,
    `- Source: ${link(s.file, `${s.repository}/blob/main/${s.file}`)} in ${link('warpdom', s.repository)} (GitHub Actions run ${s.githubRun})`,
    ...Object.entries(wpt.engines).map(
      ([name, e]) => `- ${mdxText(name)}: ${e.measured ? mdxText(e.version) : 'not measured'}`,
    ),
    '',
    `| Area | Subtests | ${measured.map(([n]) => `${mdxText(n)} passed | ${mdxText(n)} rate`).join(' | ')} |`,
    `|---|---:|${measured.map(() => '---:|---:').join('|')}|`,
  ];
  for (const area of areas) {
    const rows = measured.map(([, e]) => e.areas.find((a) => a.area === area));
    const label = area === 'total' ? '**Total**' : area === 'dom' ? `${mdxCode('dom')} (top-level files)` : mdxCode(area);
    lines.push(
      `| ${label} | ${rows[0]?.subtests ?? ''} | ${rows.map((a) => (a ? `${a.passed} | ${pct(a)}` : '- | -')).join(' | ')} |`,
    );
  }
  lines.push(
    '',
    mdxText(s.notes),
    '',
    'happy-dom and linkedom have not been run through this WPT harness, so there are no numbers for them here. The run was made with the WPT workflow in the warpdom repository; see the About page on the maintainer.',
    '',
  );
  return lines.join('\n');
}

function main() {
  const site = fileURLToPath(new URL('..', import.meta.url));
  const dataDir = join(site, '..', 'data');
  const data = JSON.parse(readFileSync(join(dataDir, 'results.json'), 'utf8'));
  const wpt = JSON.parse(readFileSync(join(dataDir, 'wpt.json'), 'utf8'));

  const idlText = readFileSync(join(dataDir, 'idl.json'), 'utf8');
  const idl = JSON.parse(idlText);
  const groupsText = readFileSync(join(dataDir, 'spec-groups.json'), 'utf8');
  const groups = JSON.parse(groupsText);
  const apiDir = join(site, 'docs', 'apis');
  rmSync(apiDir, { recursive: true, force: true });
  mkdirSync(apiDir, { recursive: true });
  for (const api of data.apis) writeFileSync(join(apiDir, `${api.id}.mdx`), renderApiPage(api, data, idl));
  writeFileSync(join(site, 'docs', 'wpt.mdx'), renderWpt(wpt));
  writeFileSync(join(site, 'sidebars.generated.json'), JSON.stringify(renderSidebar(data), null, 2) + '\n');
  for (const dir of [join(site, 'src', 'data'), join(site, 'static', 'data')]) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'results.json'), JSON.stringify(data, null, 2) + '\n');
    writeFileSync(join(dir, 'wpt.json'), JSON.stringify(wpt, null, 2) + '\n');
  }
  writeFileSync(join(site, 'src', 'data', 'idl-summary.json'), JSON.stringify(summarize(idl, groups)) + '\n');
  writeFileSync(join(site, 'src', 'data', 'site.json'), JSON.stringify({ maintainerEngine: MAINTAINER_ENGINE }) + '\n');
  writeFileSync(join(site, 'static', 'data', 'spec-groups.json'), groupsText);
  writeFileSync(join(site, 'static', 'data', 'idl.json'), idlText);
  writeFileSync(join(site, 'static', 'data', 'idl-search.json'), JSON.stringify({ engines: idl.engines.map((e) => e.engine), rows: searchRows(idl) }));
  console.log(`generated ${data.apis.length} API pages, wpt.mdx, sidebar and data files`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
